# ---- 모의 판정 (LLM 페르소나 2종; 독립 인간 평가 아님) ----
# R1: 엄격(진리조건+확신도·화행 강도 변화 = 의미 변경) / R2: 관대(명제 핵심 기준)
R1_OVR = {("A032","hedge"):"변경"}
R2_OVR = {("A006","hedge"):"유지",("A033","hedge"):"유지",("A037","hedge"):"유지",
          ("A042","hedge"):"유지",("A044","hedge"):"유지",
          ("A005","hedge"):"유보",("A008","hedge"):"유보",("A032","hedge"):"유보",("A039","hedge"):"유보"}
ADJ_OVR = {("A005","hedge"):"유보",("A008","hedge"):"유보",("A032","hedge"):"유보",("A039","hedge"):"유보"}

def judge(anchor, cat, is_control):
    if is_control:
        return "유지","유지","유지"
    r1 = R1_OVR.get((anchor,cat),"변경")
    r2 = R2_OVR.get((anchor,cat),"변경")
    fin = ADJ_OVR.get((anchor,cat),"변경")
    return r1,r2,fin

